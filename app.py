"""Slack auto-reply bot: Umer's personal retail / supply-chain assistant.

Whenever an incoming message mentions the trigger word (default "umer",
case-insensitive), the bot auto-replies on Umer's behalf, addressing the
sender. The reply is generated by fast local logic in reply_engine.build_reply
so the handler stays synchronous and well within the ~1 second latency target
(no external LLM calls in the hot path).

Runs in Socket Mode, so no public URL is required.
"""

import os
import re

from slack_bolt import App
from slack_bolt.adapter.socket_mode import SocketModeHandler

from reply_engine import build_reply

# Trigger word is configurable; default is "umer". Matched as a standalone,
# case-insensitive token so unrelated substrings won't fire it.
TRIGGER_WORD = os.environ.get("TRIGGER_WORD", "umer").strip().lower()
_TRIGGER_PATTERN = re.compile(r"\b" + re.escape(TRIGGER_WORD) + r"\b", re.IGNORECASE)

app = App(token=os.environ.get("SLACK_BOT_TOKEN"))


def _should_reply(event):
    """Decide whether this message event should trigger an auto-reply."""
    # Ignore anything the bot itself (or other bots) posted to avoid loops.
    if event.get("bot_id") or event.get("subtype") == "bot_message":
        return False
    # Ignore message edits/deletes and other subtyped events without fresh text.
    if event.get("subtype"):
        return False
    text = event.get("text")
    if not text:
        return False
    return bool(_TRIGGER_PATTERN.search(text))


@app.event("message")
def handle_message(event, say, logger):
    """Handle incoming message events and auto-reply when triggered."""
    if not _should_reply(event):
        return

    text = event.get("text", "")
    user_id = event.get("user", "there")
    reply = build_reply(text, user_id)

    # Reply in-thread if the message was itself in a thread, otherwise reply
    # in the channel. thread_ts is present on threaded messages.
    thread_ts = event.get("thread_ts") or event.get("ts")
    try:
        say(text=reply, thread_ts=thread_ts)
    except Exception:  # pragma: no cover - network/runtime failures only
        logger.exception("Failed to post auto-reply")


def main():
    handler = SocketModeHandler(app, os.environ.get("SLACK_APP_TOKEN"))
    handler.start()


if __name__ == "__main__":
    main()
